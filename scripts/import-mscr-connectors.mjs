#!/usr/bin/env node
import crypto from "node:crypto";
import fs from "node:fs";
import path from "node:path";

const IMPORTER_VERSION = "mscr-catalog-v1";
const DEFAULT_SOURCE_COMMIT = "ccadd673b87c38ec66154e6433d954a3c7707d01";
const DEFAULT_REPOSITORY_URL = "https://github.com/mindstudio-ai/mindstudio-agent";
const DEFAULT_OUT = "apps/gateway/src/generated/mscr-connector-catalog.ts";

const args = parseArgs(process.argv.slice(2));
const mscrRoot = path.resolve(args.mscrRoot ?? "");
if (!args.mscrRoot || !fs.existsSync(path.join(mscrRoot, "services"))) {
  fail("Usage: node scripts/import-mscr-connectors.mjs --mscr-root <path-to-mindstudio-agent-mscr>");
}

const outPath = path.resolve(args.out ?? DEFAULT_OUT);
const servicesRoot = path.join(mscrRoot, "services");
const sourceCommit = args.sourceCommit ?? DEFAULT_SOURCE_COMMIT;
const repositoryUrl = args.repositoryUrl ?? DEFAULT_REPOSITORY_URL;

const services = fs
  .readdirSync(servicesRoot, { withFileTypes: true })
  .filter((entry) => entry.isDirectory())
  .map((entry) => readService(entry.name))
  .sort((left, right) => left.label.localeCompare(right.label));

const actionCount = services.reduce((count, service) => count + service.actions.length, 0);
const catalog = {
  source: {
    sourceId: "mscr",
    label: "MindStudio Connector Registry",
    repositoryUrl,
    commit: sourceCommit,
    generatedAt: new Date().toISOString(),
    importerVersion: IMPORTER_VERSION,
    serviceCount: services.length,
    actionCount,
  },
  services,
};

fs.mkdirSync(path.dirname(outPath), { recursive: true });
fs.writeFileSync(
  outPath,
  [
    "/* eslint-disable */",
    "// Generated by scripts/import-mscr-connectors.mjs. Do not edit by hand.",
    "export interface MscrConnectorCatalogGenerated {",
    "  source: {",
    "    sourceId: string;",
    "    label: string;",
    "    repositoryUrl: string;",
    "    commit: string;",
    "    generatedAt: string;",
    "    importerVersion: string;",
    "    serviceCount: number;",
    "    actionCount: number;",
    "  };",
    "  services: Array<{",
    "    serviceId: string;",
    "    label: string;",
    "    description: string;",
    "    icon?: string;",
    "    auth: Array<{ id: string; type?: string; name?: string; description?: string; managed?: boolean }>;",
    "    upstreamPath: string;",
    "    actions: Array<{",
    "      serviceId: string;",
    "      actionId: string;",
    "      label: string;",
    "      description: string;",
    "      active: boolean;",
    "      configurationFields: Array<{",
    "        variable: string;",
    "        label?: string;",
    "        type?: string;",
    "        required?: boolean;",
    "        helpText?: string;",
    "        groupTitle?: string;",
    "      }>;",
    "      upstreamPath: string;",
    "      handlerSha256?: string;",
    "      docsPreview?: string;",
    "    }>;",
    "  }>;",
    "}",
    `export const MSCR_CONNECTOR_CATALOG: MscrConnectorCatalogGenerated = ${JSON.stringify(catalog, null, 2)};`,
    "",
  ].join("\n"),
);

console.log(
  `Imported ${catalog.source.serviceCount} MSCR services and ${catalog.source.actionCount} actions into ${path.relative(process.cwd(), outPath)}`,
);

function readService(serviceDirName) {
  const serviceDir = path.join(servicesRoot, serviceDirName);
  const serviceYaml = readText(path.join(serviceDir, "service.yml"));
  const metadata = readMetadata(serviceYaml);
  const serviceId = readScalar(serviceYaml, "id") ?? slugify(serviceDirName);
  const actions = fs
    .readdirSync(serviceDir, { withFileTypes: true })
    .filter((entry) => entry.isDirectory() && fs.existsSync(path.join(serviceDir, entry.name, "connector.yml")))
    .map((entry) => readAction(serviceDirName, serviceId, entry.name))
    .sort((left, right) => left.label.localeCompare(right.label));

  return {
    serviceId,
    label: metadata.name ?? serviceDirName,
    description: metadata.description ?? "",
    icon: metadata.icon,
    auth: readServiceConfiguration(serviceYaml),
    upstreamPath: posixPath("services", serviceDirName, "service.yml"),
    actions,
  };
}

function readAction(serviceDirName, serviceId, actionDirName) {
  const actionDir = path.join(servicesRoot, serviceDirName, actionDirName);
  const actionYamlPath = path.join(actionDir, "connector.yml");
  const actionYaml = readText(actionYamlPath);
  const metadata = readMetadata(actionYaml);
  const actionId = readScalar(actionYaml, "id") ?? slugify(actionDirName);
  const handlerPath = path.join(actionDir, "handler.ts");
  const readmePath = path.join(actionDir, "readme.md");
  return {
    serviceId,
    actionId,
    label: metadata.name ?? actionDirName,
    description: metadata.description ?? "",
    active: readScalar(actionYaml, "active") !== false,
    configurationFields: readActionConfiguration(actionYaml),
    upstreamPath: posixPath("services", serviceDirName, actionDirName),
    handlerSha256: fs.existsSync(handlerPath) ? sha256(readText(handlerPath)) : undefined,
    docsPreview: fs.existsSync(readmePath) ? compactMarkdownPreview(readText(readmePath)) : undefined,
  };
}

function readMetadata(text) {
  const block = readIndentedBlock(text, "metadata", 0);
  return {
    name: readScalar(block, "name"),
    description: readScalar(block, "description"),
    icon: readScalar(block, "icon"),
  };
}

function readServiceConfiguration(text) {
  const block = readIndentedBlock(text, "configuration", 0);
  return splitListItems(block, 2)
    .map((item) => ({
      id: readScalar(item, "id"),
      type: readScalar(item, "type"),
      name: readScalar(item, "name"),
      description: readScalar(item, "description"),
      managed: readScalar(item, "managed"),
    }))
    .filter((item) => typeof item.id === "string" && item.id.length > 0);
}

function readActionConfiguration(text) {
  const block = readIndentedBlock(text, "configuration", 0);
  return splitListItems(block, 2).flatMap((group) => {
    const groupTitle = readScalar(group, "title");
    return splitListItems(group, 6)
      .map((item) => ({
        variable: readScalar(item, "variable"),
        label: readScalar(item, "label"),
        type: readScalar(item, "type"),
        required: readScalar(item, "required"),
        helpText: readScalar(item, "helpText"),
        groupTitle,
      }))
      .filter((item) => typeof item.variable === "string" && item.variable.length > 0);
  });
}

function readIndentedBlock(text, key, indent) {
  const lines = text.split(/\r?\n/);
  const start = lines.findIndex((line) => countIndent(line) === indent && line.trim() === `${key}:`);
  if (start < 0) {
    return "";
  }
  const result = [];
  for (const line of lines.slice(start + 1)) {
    if (line.trim() && countIndent(line) <= indent) {
      break;
    }
    result.push(line);
  }
  return result.join("\n");
}

function splitListItems(block, indent) {
  const items = [];
  let current = [];
  for (const line of block.split(/\r?\n/)) {
    if (countIndent(line) === indent && line.trim().startsWith("- ")) {
      if (current.length) {
        items.push(current.join("\n"));
      }
      current = [line];
      continue;
    }
    if (current.length) {
      current.push(line);
    }
  }
  if (current.length) {
    items.push(current.join("\n"));
  }
  return items;
}

function readScalar(text, key) {
  const pattern = new RegExp(`^\\s*(?:-\\s*)?${escapeRegExp(key)}:\\s*(.*)$`, "m");
  const match = text.match(pattern);
  if (!match) {
    return undefined;
  }
  return parseScalar(match[1] ?? "");
}

function parseScalar(raw) {
  const trimmed = raw.trim();
  if (!trimmed) {
    return "";
  }
  if (trimmed === "true") {
    return true;
  }
  if (trimmed === "false") {
    return false;
  }
  if (trimmed === "null") {
    return undefined;
  }
  if ((trimmed.startsWith("'") && trimmed.endsWith("'")) || (trimmed.startsWith('"') && trimmed.endsWith('"'))) {
    return trimmed.slice(1, -1).replace(/''/g, "'");
  }
  return trimmed;
}

function compactMarkdownPreview(text) {
  return text
    .replace(/\r/g, "")
    .split("\n")
    .map((line) => line.trim())
    .filter(Boolean)
    .slice(0, 18)
    .join("\n")
    .slice(0, 1600);
}

function countIndent(line) {
  const match = line.match(/^ */);
  return match ? match[0].length : 0;
}

function readText(filePath) {
  return fs.readFileSync(filePath, "utf8");
}

function sha256(value) {
  return crypto.createHash("sha256").update(value).digest("hex");
}

function slugify(value) {
  return value
    .trim()
    .replace(/([a-z0-9])([A-Z])/g, "$1-$2")
    .replace(/[^a-zA-Z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "")
    .toLowerCase();
}

function posixPath(...parts) {
  return parts.join("/");
}

function parseArgs(argv) {
  const parsed = {};
  for (let index = 0; index < argv.length; index += 1) {
    const arg = argv[index];
    if (!arg?.startsWith("--")) {
      continue;
    }
    const key = arg.slice(2).replace(/-([a-z])/g, (_, char) => char.toUpperCase());
    parsed[key] = argv[index + 1];
    index += 1;
  }
  return parsed;
}

function escapeRegExp(value) {
  return value.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
}

function fail(message) {
  console.error(message);
  process.exit(1);
}
