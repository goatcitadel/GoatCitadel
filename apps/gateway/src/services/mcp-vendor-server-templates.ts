import type { McpServerCategory, McpServerTemplateRecord } from "@goatcitadel/contracts";

/**
 * Vendor-hosted remote MCP servers reviewed in Hermes Agent's `optional-mcps` catalog
 * (MIT, Nous Research, upstream commit 07ee800dc7). Each URL is the vendor's documented endpoint;
 * sign-in uses MCP metadata discovery. Regenerate from the upstream manifests rather than editing by hand.
 * Every entry stays restricted, approval-first and disabled until an operator creates and connects it.
 */
export const MCP_VENDOR_CATALOG_PROVENANCE = {
  catalog: "hermes-agent/optional-mcps",
  catalogLicense: "MIT",
  catalogCommit: "07ee800dc7",
} as const;

interface VendorTemplateInput {
  templateId: string;
  label: string;
  description: string;
  transport: "http" | "sse";
  url: string;
  oauth: boolean;
  category: McpServerCategory;
  costTier?: McpServerTemplateRecord["costTier"];
  documentationUrl: string;
  riskNotes?: string[];
}

function vendorTemplate(input: VendorTemplateInput): McpServerTemplateRecord {
  return {
    templateId: input.templateId,
    label: input.label,
    description: input.description,
    transport: input.transport,
    url: input.url,
    authType: input.oauth ? "oauth2" : "none",
    ...(input.oauth ? { oauth: { metadataDiscovery: true } } : {}),
    category: input.category,
    trustTier: "restricted",
    costTier: input.costTier ?? "mixed",
    policy: {
      requireFirstToolApproval: true,
      redactionMode: "strict",
      allowedToolPatterns: [],
      blockedToolPatterns: [],
    },
    enabledByDefault: false,
    networkHosts: [new URL(input.url).host],
    provenance: { ...MCP_VENDOR_CATALOG_PROVENANCE, documentationUrl: input.documentationUrl },
    ...(input.riskNotes ? { riskNotes: input.riskNotes } : {}),
  };
}

